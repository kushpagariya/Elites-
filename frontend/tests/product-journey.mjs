 await page.goto(base+'/app/scenarios');
 await page.getByRole('button',{name:'Reset edits',exact:true}).click();
 assert.equal((await api('/projects/demo/workspace')).evaluation_id,baseline.evaluation_id);
 await page.getByLabel('Scenario name',{exact:true}).fill('Zero-effect rent review');
 await page.getByLabel('Area-wide rent change (%)',{exact:true}).fill('-10');
