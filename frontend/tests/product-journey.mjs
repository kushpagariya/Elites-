 const saved=state;
 await page.getByRole('button',{name:'Save & analyse changes',exact:true}).click();
 assert.equal((await api('/projects/demo/workspace')).scenario_id,saved.scenario_id);
 await page.reload();
 await page.getByRole('heading',{name:'Before & after',exact:true}).waitFor();
 await page.getByText(/Both use their saved analysis snapshots/).waitFor();
