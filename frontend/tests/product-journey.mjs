import path from 'node:path';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.STORESCOUT_PLAYWRIGHT ?? 'playwright');
const base=process.env.STORESCOUT_UI ?? 'http://127.0.0.1:3011';
