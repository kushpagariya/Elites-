 check('reset preserves saved evaluation; switching infrastructure retains deliberate zero effect');
 await page.getByRole('button',{name:'Save & analyse changes',exact:true}).click();
 await page.getByText('Analysis ready. Locations and insights now use this saved scenario.',{exact:true}).waitFor();
